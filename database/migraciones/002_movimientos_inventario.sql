SET DEFINE OFF

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'MOVIMIENTOS_INVENTARIO';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE MOVIMIENTOS_INVENTARIO ('
            || 'ID_MOVIMIENTO NUMBER PRIMARY KEY, '
            || 'ID_PRODUCTO NUMBER NOT NULL, '
            || 'FECHA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, '
            || 'TIPO VARCHAR2(20) NOT NULL, '
            || 'CANTIDAD NUMBER NOT NULL, '
            || 'REFERENCIA VARCHAR2(100), '
            || 'CONSTRAINT FK_MOV_INV_PRODUCTO FOREIGN KEY (ID_PRODUCTO) REFERENCES PRODUCTOS (ID_PRODUCTO), '
            || 'CONSTRAINT CK_MOV_INV_CANTIDAD CHECK (CANTIDAD <> 0), '
            || 'CONSTRAINT CK_MOV_INV_TIPO CHECK (TIPO IN (''ABASTECIMIENTO'', ''VENTA'', ''CANJE'', ''AJUSTE'')))';
    END IF;
    SELECT COUNT(*) INTO v_count FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'SEQ_MOVIMIENTOS_INVENTARIO';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_MOVIMIENTOS_INVENTARIO START WITH 1 INCREMENT BY 1';
    END IF;
END;
/

COMMIT;
