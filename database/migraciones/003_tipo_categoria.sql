SET DEFINE OFF
SET SERVEROUTPUT ON

DECLARE
    v_columna NUMBER;
    v_restriccion NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_columna
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'CATEGORIAS' AND COLUMN_NAME = 'TIPO';

    SELECT COUNT(*) INTO v_restriccion
    FROM USER_CONSTRAINTS
    WHERE TABLE_NAME = 'CATEGORIAS' AND CONSTRAINT_NAME = 'CK_CATEGORIAS_TIPO';

    IF v_restriccion > 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE CATEGORIAS DROP CONSTRAINT CK_CATEGORIAS_TIPO';
    END IF;

    IF v_columna = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE CATEGORIAS ADD (TIPO VARCHAR2(20) DEFAULT ''EXTRA'' NOT NULL)';
        EXECUTE IMMEDIATE 'UPDATE CATEGORIAS SET TIPO = ''COMIDA'' '
            || 'WHERE UPPER(NOMBRE) LIKE ''S_NDWICH%'' OR UPPER(NOMBRE) LIKE ''COMIDA%''';
        EXECUTE IMMEDIATE 'UPDATE CATEGORIAS SET TIPO = ''BEBIDA'' WHERE UPPER(NOMBRE) LIKE ''BEBIDA%''';
        EXECUTE IMMEDIATE 'UPDATE CATEGORIAS SET TIPO = ''ACOMPANAMIENTO'' '
            || 'WHERE UPPER(NOMBRE) LIKE ''ACOMPA%''';
        DBMS_OUTPUT.PUT_LINE('Columna TIPO creada y categorías clasificadas por nombre.');
    ELSE
        EXECUTE IMMEDIATE 'ALTER TABLE CATEGORIAS MODIFY (TIPO DEFAULT ''EXTRA'')';
        EXECUTE IMMEDIATE 'UPDATE CATEGORIAS SET TIPO = ''COMIDA'' WHERE TIPO = ''SANDWICH''';
        EXECUTE IMMEDIATE 'UPDATE CATEGORIAS SET TIPO = ''EXTRA'' '
            || 'WHERE TIPO NOT IN (''COMIDA'', ''BEBIDA'', ''ACOMPANAMIENTO'')';
        DBMS_OUTPUT.PUT_LINE('Tipos existentes convertidos: SANDWICH a COMIDA y OTRO a EXTRA.');
    END IF;

    EXECUTE IMMEDIATE 'ALTER TABLE CATEGORIAS ADD CONSTRAINT CK_CATEGORIAS_TIPO '
        || 'CHECK (TIPO IN (''COMIDA'', ''BEBIDA'', ''ACOMPANAMIENTO'', ''EXTRA''))';
    COMMIT;
END;
/

SELECT ID_CATEGORIA, NOMBRE, TIPO, ACTIVO FROM CATEGORIAS ORDER BY ID_CATEGORIA;
