SET DEFINE OFF
SET SERVEROUTPUT ON

DECLARE
    v_acompanamiento VARCHAR2(50) := UNISTR('ACOMPA\00D1AMIENTO');
    v_existe NUMBER;
BEGIN
    UPDATE PREMIOS SET NOMBRE = 'Bebida', DESCRIPCION = 'Canje por una bebida.'
    WHERE UPPER(NOMBRE) LIKE 'BEBIDA%';

    UPDATE PREMIOS SET NOMBRE = UNISTR('Acompa\00F1amiento'),
        DESCRIPCION = UNISTR('Canje por un acompa\00F1amiento.')
    WHERE UPPER(NOMBRE) LIKE 'ACOMPA%';

    UPDATE PREMIOS SET NOMBRE = UNISTR('S\00E1ndwich'),
        DESCRIPCION = UNISTR('Canje por un s\00E1ndwich.')
    WHERE UPPER(NOMBRE) LIKE 'S%NDWICH%';

    UPDATE PREMIOS SET NOMBRE = UNISTR('Men\00FA completo'),
        DESCRIPCION = UNISTR('Canje por un men\00FA completo.')
    WHERE UPPER(NOMBRE) LIKE 'MEN%COMPLETO%';

    UPDATE PRODUCTOS SET NOMBRE = UNISTR('S\00E1ndwich de prueba') WHERE CODIGO = 'DEMO-SANDWICH';
    UPDATE PRODUCTOS SET NOMBRE = UNISTR('Acompa\00F1amiento de prueba') WHERE CODIGO = 'DEMO-ACOMP';
    UPDATE MENUS SET NOMBRE = UNISTR('Men\00FA de prueba') WHERE ID_MENU = 9001;

    UPDATE CATEGORIAS SET DESCRIPCION = UNISTR('S\00E1ndwiches individuales')
    WHERE UPPER(NOMBRE) = 'SANDWICH';

    FOR c IN (SELECT ID_CATEGORIA, NOMBRE, ACTIVO, TIPO FROM CATEGORIAS
              WHERE UPPER(NOMBRE) LIKE 'ACOMPA%AMIENTO'
              AND INSTR(NOMBRE, UNISTR('\00C3')) > 0) LOOP
        SELECT COUNT(*) INTO v_existe FROM CATEGORIAS WHERE NOMBRE = v_acompanamiento;
        IF v_existe = 0 THEN
            INSERT INTO CATEGORIAS (ID_CATEGORIA, NOMBRE, DESCRIPCION, ACTIVO, TIPO)
            VALUES (SEQ_CATEGORIAS.NEXTVAL, v_acompanamiento,
                    UNISTR('Acompa\00F1amientos'), c.ACTIVO, c.TIPO);
        END IF;
        UPDATE PRODUCTOS SET CATEGORIA = v_acompanamiento WHERE CATEGORIA = c.NOMBRE;
        DELETE FROM CATEGORIAS WHERE ID_CATEGORIA = c.ID_CATEGORIA;
        DBMS_OUTPUT.PUT_LINE('Categoría corregida: ' || c.NOMBRE || ' -> ' || v_acompanamiento);
    END LOOP;

    UPDATE CATEGORIAS SET DESCRIPCION = UNISTR('Acompa\00F1amientos')
    WHERE NOMBRE = v_acompanamiento;

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Textos corregidos.');
END;
/

SELECT NOMBRE, DESCRIPCION, PUNTOS_REQUERIDOS FROM PREMIOS ORDER BY PUNTOS_REQUERIDOS;
