DECLARE
    v_nullable USER_TAB_COLUMNS.NULLABLE%TYPE;
BEGIN
    SELECT NULLABLE INTO v_nullable
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'CLIENTES' AND COLUMN_NAME = 'NIT';
    IF v_nullable = 'N' THEN
        EXECUTE IMMEDIATE 'ALTER TABLE CLIENTES MODIFY (NIT NULL)';
    END IF;
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'PREMIOS' AND COLUMN_NAME = 'ID_PRODUCTO';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE PREMIOS ADD (ID_PRODUCTO NUMBER NULL)';
    END IF;
    SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'PREMIOS' AND COLUMN_NAME = 'ID_MENU';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE PREMIOS ADD (ID_MENU NUMBER NULL)';
    END IF;
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME = 'FK_PREMIO_PRODUCTO';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE PREMIOS ADD CONSTRAINT FK_PREMIO_PRODUCTO FOREIGN KEY (ID_PRODUCTO) REFERENCES PRODUCTOS (ID_PRODUCTO)';
    END IF;
    SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME = 'FK_PREMIO_MENU';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE PREMIOS ADD CONSTRAINT FK_PREMIO_MENU FOREIGN KEY (ID_MENU) REFERENCES MENUS (ID_MENU)';
    END IF;
    SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME = 'CK_PREMIO_DESTINO';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE PREMIOS ADD CONSTRAINT CK_PREMIO_DESTINO CHECK ((ID_PRODUCTO IS NULL AND ID_MENU IS NULL) OR (ID_PRODUCTO IS NOT NULL AND ID_MENU IS NULL) OR (ID_PRODUCTO IS NULL AND ID_MENU IS NOT NULL))';
    END IF;
END;
