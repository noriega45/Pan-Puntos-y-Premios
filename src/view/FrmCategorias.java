    private void btnGuardarCategoriaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarCategoriaActionPerformed
        // TODO add your handling code here:
        
String nombre = txtNombreCategoria.getText().trim();
String descripcion = txtDescripcionCategoria.getText().trim();

if (nombre.isEmpty()) {
    JOptionPane.showMessageDialog(
        this,
        "El nombre de la categoría es obligatorio.",
        "Aviso",
        JOptionPane.WARNING_MESSAGE
    );
    return;
}

Categoria categoria = new Categoria(0, nombre, descripcion);

if (categoriaController.guardarCategoria(categoria)) {
    JOptionPane.showMessageDialog(
        this,
        "Categoría guardada correctamente."
    );

    txtNombreCategoria.setText("");
    txtDescripcionCategoria.setText("");
    idCategoriaSeleccionada = 0;

    cargarCategorias();
} else {
    JOptionPane.showMessageDialog(
        this,
        "No se pudo guardar la categoría. "
        + "Verifica si el nombre ya existe.",
        "Error",
        JOptionPane.ERROR_MESSAGE
    );
}

    }//GEN-LAST:event_btnGuardarCategoriaActionPerformed

    private void tblCategoriasMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCategoriasMouseClicked
        // TODO add your handling code here:
            int fila = tblCategorias.getSelectedRow();

if (fila >= 0) {
    idCategoriaSeleccionada = Integer.parseInt(
        tblCategorias.getValueAt(fila, 0).toString()
    );

    txtNombreCategoria.setText(
        tblCategorias.getValueAt(fila, 1).toString()
    );

    Object descripcion =
        tblCategorias.getValueAt(fila, 2);

    txtDescripcionCategoria.setText(
        descripcion == null ? "" : descripcion.toString()
    );
}
    }//GEN-LAST:event_tblCategoriasMouseClicked

    private void btnEditarCategoriaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarCategoriaActionPerformed
        // TODO add your handling code here:
            
if (idCategoriaSeleccionada <= 0) {
    JOptionPane.showMessageDialog(
        this,
        "Selecciona una categoría de la tabla para editar.",
        "Aviso",
        JOptionPane.WARNING_MESSAGE
    );
    return;
}

String nombre = txtNombreCategoria.getText().trim();
String descripcion = txtDescripcionCategoria.getText().trim();

if (nombre.isEmpty()) {
    JOptionPane.showMessageDialog(
        this,
        "El nombre de la categoría es obligatorio.",
        "Aviso",
        JOptionPane.WARNING_MESSAGE
    );
    return;
}

Categoria categoria = new Categoria(
    idCategoriaSeleccionada,
    nombre,
    descripcion
);

if (categoriaController.actualizarCategoria(categoria)) {
    JOptionPane.showMessageDialog(
        this,
        "Categoría actualizada correctamente."
    );

    txtNombreCategoria.setText("");
    txtDescripcionCategoria.setText("");
    idCategoriaSeleccionada = 0;

    cargarCategorias();
} else {
    JOptionPane.showMessageDialog(
        this,
        "No se pudo actualizar la categoría. "
        + "Verifica si el nombre ya existe o está relacionado con productos.",
        "Error",
        JOptionPane.ERROR_MESSAGE
    );
}

    }//GEN-LAST:event_btnEditarCategoriaActionPerformed

    private void btnDesactivarCategoriaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDesactivarCategoriaActionPerformed
        // TODO add your handling code here:
            
if (idCategoriaSeleccionada <= 0) {
    JOptionPane.showMessageDialog(
        this,
        "Selecciona una categoría de la tabla para desactivar.",
        "Aviso",
        JOptionPane.WARNING_MESSAGE
    );
    return;
}

int confirmacion = JOptionPane.showConfirmDialog(
    this,
    "¿Seguro que deseas desactivar esta categoría?",
    "Confirmar desactivación",
    JOptionPane.YES_NO_OPTION,
    JOptionPane.WARNING_MESSAGE
);

if (confirmacion != JOptionPane.YES_OPTION) {
    return;
}

if (categoriaController.desactivarCategoria(idCategoriaSeleccionada)) {
    JOptionPane.showMessageDialog(
        this,
        "Categoría desactivada correctamente."
    );

    txtNombreCategoria.setText("");
    txtDescripcionCategoria.setText("");
    idCategoriaSeleccionada = 0;

    cargarCategorias();
} else {
    JOptionPane.showMessageDialog(
        this,
        "No se pudo desactivar la categoría.",
        "Error",
        JOptionPane.ERROR_MESSAGE
    );
}

    }//GEN-LAST:event_btnDesactivarCategoriaActionPerformed

